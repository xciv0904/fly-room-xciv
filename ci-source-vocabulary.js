function ciSourceMeaning(word){
  const key=String(word||"").trim().toLowerCase().replace(/’/g,"'");
  const lookup=k=>{
    const plain=k.normalize("NFD").replace(/\p{M}/gu,"");
    return PRONUNCIATION_ZH[k]||CI_VOCABULARY_ZH[k]||CI_SOURCE_VOCABULARY[k]||PRONUNCIATION_ZH[plain]||CI_VOCABULARY_ZH[plain]||CI_SOURCE_VOCABULARY[plain]||"";
  };
  if(lookup(key))return lookup(key);
  if(/^\d+(?:[./-]\d+)*$/.test(key))return `數字：${key}`;
  if(/^\d+(?:st|nd|rd|th)?-century$/.test(key))return `第 ${parseInt(key,10)} 世紀的`;
  const root=key.replace(/'s$/,""),variants=[root];
  if(root.endsWith("ies"))variants.push(root.slice(0,-3)+"y");
  if(root.endsWith("s"))variants.push(root.slice(0,-1));
  if(root.endsWith("es"))variants.push(root.slice(0,-2));
  if(root.endsWith("ied"))variants.push(root.slice(0,-3)+"y");
  if(root.endsWith("ed"))variants.push(root.slice(0,-1),root.slice(0,-2),root.slice(0,-3));
  if(root.endsWith("ing"))variants.push(root.slice(0,-3),root.slice(0,-3)+"e",root.slice(0,-4));
  for(const candidate of variants){const meaning=lookup(candidate);if(meaning)return meaning;}
  return "";
}

function ciWordSentence(word,text){
  const normalize=t=>String(t||"").replace(/’/g,"'").toLowerCase();
  const aliases={pok:"pokémon","mon-themed":"pokémon-themed",ckler:"glöckler",cklers:"glöcklers",poml:"pomlázka","paper-m":"paper-mâché"};
  const normalized=normalize(word);
  const target=(aliases[normalized]||normalized).replace(/[.*+?^${}()|[\]\\]/g,"\\$&");
  if(!target)return "";
  const boundary=/^\d/.test(normalized)?"\\p{N}":"\\p{Script=Latin}";
  const match=new RegExp(`(^|[^${boundary}])${target}(?![${boundary}])`,"u");
  const sentences=typeof Intl.Segmenter==="function"?Array.from(new Intl.Segmenter("en",{granularity:"sentence"}).segment(String(text||"")),x=>x.segment):String(text||"").split(/(?<=[.!?])\s+/);
  return sentences.map(x=>x.trim()).find(x=>match.test(normalize(x)))||"";
}
function ciWordContext(word,context=""){
  const sentence=ciWordSentence(word,context);
  if(sentence)return sentence;
  const source=[...CI_PDF_DRILLS,...CI_NEWS_RELEASES,...CI_EXTERNAL_BROADCASTS].find(d=>ciWordSentence(word,d.text));
  return source?ciWordSentence(word,source.text):"";
}
